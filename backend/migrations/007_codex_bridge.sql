CREATE TABLE codex_bridge_requests (
  id CHAR(36) PRIMARY KEY,
  job_id CHAR(36) NOT NULL,
  attempt INT UNSIGNED NOT NULL,
  agent_task_id CHAR(36) NULL,
  kind ENUM('ANALYZE','LESSON','QUIZ','SCENE','REGENERATE') NOT NULL,
  payload JSON NOT NULL,
  output_schema JSON NOT NULL,
  status ENUM('PENDING','PROCESSING','COMPLETED','FAILED','CANCELLED') NOT NULL DEFAULT 'PENDING',
  claim_token CHAR(64) NULL,
  claimed_by VARCHAR(100) NULL,
  lease_expires_at DATETIME(3) NULL,
  output_json JSON NULL,
  error_message VARCHAR(180) NULL,
  started_at DATETIME(3) NULL,
  completed_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (job_id) REFERENCES generation_jobs(id) ON DELETE CASCADE,
  FOREIGN KEY (agent_task_id) REFERENCES generation_agent_tasks(id) ON DELETE CASCADE,
  INDEX idx_codex_pending (status,created_at),
  INDEX idx_codex_lease (status,lease_expires_at),
  INDEX idx_codex_job_attempt (job_id,attempt,agent_task_id)
);
