CREATE TABLE IF NOT EXISTS generation_agent_tasks (
  id CHAR(36) PRIMARY KEY,
  job_id CHAR(36) NOT NULL,
  attempt INT UNSIGNED NOT NULL,
  task_order INT UNSIGNED NOT NULL,
  role ENUM('ANALYST','PLANNER','SCENE_SPECIALIST','QUIZ_SPECIALIST','VALIDATOR') NOT NULL,
  name VARCHAR(100) NOT NULL,
  scene_id VARCHAR(64) NULL,
  status ENUM('PENDING','PROCESSING','COMPLETED','FAILED','CANCELLED') NOT NULL DEFAULT 'PENDING',
  progress TINYINT UNSIGNED NOT NULL DEFAULT 0,
  current_step VARCHAR(180) NOT NULL DEFAULT 'Waiting for the shared plan',
  provider VARCHAR(40) NOT NULL,
  model VARCHAR(100) NULL,
  tokens_input INT UNSIGNED NOT NULL DEFAULT 0,
  tokens_output INT UNSIGNED NOT NULL DEFAULT 0,
  estimated_cost DECIMAL(12,6) NOT NULL DEFAULT 0,
  error_message VARCHAR(500) NULL,
  started_at DATETIME(3) NULL,
  completed_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (job_id) REFERENCES generation_jobs(id) ON DELETE CASCADE,
  UNIQUE KEY uq_agent_attempt_order (job_id,attempt,task_order),
  INDEX idx_agent_job_attempt_status (job_id,attempt,status)
);
